#!/usr/bin/env python3
"""Rewrite the command lists of the browser's SPL guard from the Python policy (D-080).

The lists in ``sunavigator/appserver/static/ucm_common.js`` are generated between
``/* BEGIN generated guard lists */`` and ``/* END generated guard lists */``. Run this after
changing a list in ``splunk_ucm/spl``; ``tests/unit/test_spl_guard_parity.py`` fails when they differ.
"""
import os
import sys
import textwrap

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "sunavigator", "lib"))

from splunk_ucm.spl.analysis import GENERATING_COMMANDS, INDIRECT_COMMANDS, SIDE_EFFECT_COMMANDS  # noqa: E402
from splunk_ucm.spl.policy import HIDDEN_SPL_COMMANDS, READ_ONLY_COMMANDS  # noqa: E402

TARGET = os.path.join(ROOT, "sunavigator", "appserver", "static", "ucm_common.js")
BEGIN = "/* BEGIN generated guard lists */"
END = "/* END generated guard lists */"
LISTS = [
    ("SIDE_EFFECT_COMMANDS", SIDE_EFFECT_COMMANDS),
    ("INDIRECT_COMMANDS", INDIRECT_COMMANDS),
    ("HIDDEN_SPL_COMMANDS", HIDDEN_SPL_COMMANDS),
    ("GENERATING_COMMANDS", GENERATING_COMMANDS),
    ("READ_ONLY_COMMANDS", READ_ONLY_COMMANDS),
]


def render():
    out = ["    " + BEGIN, "    /* Generated by tools/sync_guard_lists.py from splunk_ucm/spl; do not edit by hand. */"]
    for name, values in LISTS:
        body = ", ".join('"%s"' % v for v in sorted(values))
        wrapped = textwrap.fill(body, width=108, initial_indent="    var %s = [" % name,
                                subsequent_indent="        ", break_long_words=False)
        out.append(wrapped + "];")
    out.append("    " + END)
    return "\n".join(out)


def main(check=False):
    with open(TARGET, encoding="utf-8") as handle:
        text = handle.read()
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    head = text[:start].rstrip(" ")
    new = head + render() + text[stop:]
    if check:
        return 0 if new == text else 1
    with open(TARGET, "w", encoding="utf-8") as handle:
        handle.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
