"""Create, update and delete dashboards generated from templates (D-032).

Views are written to this app with the system token after the REST handler
has checked ``ucm_deploy``. Only template output is ever written, and only
views whose record exists in ``uc_dashboards`` and whose XML carries the
marker are updated or deleted.
"""

import json
from typing import Any, Dict, List, Optional
from urllib.parse import quote

from .. import APP_NAME
from ..audit import AuditService
from ..errors import ConflictError, NotFoundError, StorageError, ValidationError
from ..storage import collections as C
from ..storage.collections import DOC_SCHEMA
from ..storage.kvstore import DocumentStore
from ..storage.transport import SplunkdTransport
from ..util import safe_key, sha256_text, utc_now_iso
from .templates import MARKER, render, template_list, view_name


class ViewClient:
    def __init__(self, transport: SplunkdTransport, app: str = APP_NAME):
        self.t = transport
        self.base = "/servicesNS/nobody/%s/data/ui/views" % quote(app, safe="")

    def get(self, name: str) -> Optional[str]:
        status, body = self.t.request("GET", "%s/%s" % (self.base, quote(name, safe="")), {"output_mode": "json"})
        if status == 404:
            return None
        if status != 200:
            raise StorageError("view read failed", status)
        entries = json.loads(body.decode("utf-8") or "{}").get("entry") or []
        return (entries[0].get("content") or {}).get("eai:data") if entries else None

    def save(self, name: str, xml: str, exists: bool) -> None:
        if exists:
            status, body = self.t.request("POST", "%s/%s" % (self.base, quote(name, safe="")),
                                          {"output_mode": "json"}, form={"eai:data": xml})
        else:
            status, body = self.t.request("POST", self.base, {"output_mode": "json"},
                                          form={"name": name, "eai:data": xml})
        if status not in (200, 201):
            raise StorageError("view write failed", status, {"body": body[:300].decode("utf-8", "replace")})

    def delete(self, name: str) -> None:
        status, _ = self.t.request("DELETE", "%s/%s" % (self.base, quote(name, safe="")), {"output_mode": "json"})
        if status not in (200, 404):
            raise StorageError("view delete failed", status)


class DashboardService:
    def __init__(self, store: DocumentStore, audit: AuditService, views: Optional[ViewClient]):
        self.store = store
        self.audit = audit
        self.views = views

    def templates(self) -> List[Dict[str, Any]]:
        return template_list()

    def list(self) -> List[Dict[str, Any]]:
        return self.store.query(C.DASHBOARDS, None, sort=[("updated_at", -1)], limit=200,
                                fields=["name", "template", "params", "label", "updated_at", "updated_by",
                                        "created_at", "created_by", "xml_sha256"])

    def _context(self) -> Dict[str, Any]:
        deployed = []
        for d in self.store.query(C.DEPLOYMENTS, {"deployed_revision": {"$gte": 1}},
                                  fields=["catalog_key", "title", "saved_search", "live_status"], limit=500):
            catalog = self.store.get(C.CATALOG, d.get("catalog_key") or "") or {}
            deployed.append({"title": d.get("title") or catalog.get("title", ""),
                             "saved_search": (d.get("saved_search") or {}).get("name", ""),
                             "live_status": d.get("live_status"), "domains": catalog.get("domains") or []})
        deployed.sort(key=lambda s: (s["live_status"] != "enabled", s["title"]))
        return {"deployed": deployed}

    def preview(self, template: str, params: Dict[str, Any]) -> Dict[str, Any]:
        params = self._params(params)
        out = render(template, params, self._context())
        return {"template": template, "params": params, "name": view_name(template, params),
                "label": out["label"], "xml": out["xml"]}

    def create(self, actor: str, template: str, params: Dict[str, Any]) -> Dict[str, Any]:
        if self.views is None:
            raise ValidationError("dashboard creation is not available in this context")
        prev = self.preview(template, params)
        name = prev["name"]
        key = safe_key("dash", name)
        record = self.store.get(C.DASHBOARDS, key)
        existing = self.views.get(name)
        if existing is not None and (record is None or MARKER not in existing):
            raise ConflictError("a view named %s exists and was not generated by this app" % name,
                                {"code": "name_conflict"})
        self.views.save(name, prev["xml"], exists=existing is not None)
        now = utc_now_iso()
        doc = {"_key": key, "doc_schema": DOC_SCHEMA, "name": name, "template": template,
               "params": prev["params"], "label": prev["label"], "xml_sha256": sha256_text(prev["xml"]),
               "created_at": (record or {}).get("created_at") or now, "created_by": (record or {}).get("created_by")
               or actor, "updated_at": now, "updated_by": actor}
        self.store.upsert(C.DASHBOARDS, doc)
        self.audit.record(actor, "dashboard.created" if record is None else "dashboard.updated", "dashboard", name,
                          details={"template": template, "params": prev["params"]})
        return doc

    def delete(self, actor: str, name: str) -> None:
        if self.views is None:
            raise ValidationError("dashboard deletion is not available in this context")
        key = safe_key("dash", name)
        if self.store.get(C.DASHBOARDS, key) is None:
            raise NotFoundError("dashboard not generated by this app")
        existing = self.views.get(name)
        if existing is not None:
            if MARKER not in existing:
                raise ConflictError("view %s no longer carries the app marker; delete it in Splunk" % name)
            self.views.delete(name)
        self.store.delete(C.DASHBOARDS, key)
        self.audit.record(actor, "dashboard.deleted", "dashboard", name)

    @staticmethod
    def _params(params: Any) -> Dict[str, Any]:
        if not isinstance(params, dict):
            raise ValidationError("params must be an object")
        return {k: str(v) for k, v in params.items() if k in ("domain",) and v not in (None, "")}
