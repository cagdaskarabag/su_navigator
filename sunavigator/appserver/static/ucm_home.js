/*
 * ucm_common.js is requested from the same static directory as ucm.css, which the dashboard
 * XML loads under /static/@<build>.<push>-<app build>/... and so carries the app build.
 * A relative module id ("../app/sunavigator/ucm_common") or splunk.util.make_url (which
 * always writes app build 0) would leave it cached for a year across upgrades.
 */
var ucmCommonUrl = (function () {
    var links = document.querySelectorAll('link[href*="/app/sunavigator/ucm.css"]');
    return links.length ? links[0].href.replace(/ucm\.css([?#].*)?$/, "ucm_common.js") : "../app/sunavigator/ucm_common";
}());

require(["jquery", ucmCommonUrl, "splunkjs/mvc/simplexml/ready!"], ucmViewMain);

function ucmViewMain($, ucm) {
    "use strict";
    var el = ucm.el;
    var root = document.getElementById("ucm-home");

    /* Same ids and order as the Domain dashboard dropdown and ucm.DOMAINS (checked by a unit test). */
    var DOMAIN_LABELS = [
        ["security", "Security"], ["infrastructure", "Infrastructure"], ["network", "Network"],
        ["application", "Application"], ["database", "Database"], ["cloud", "Cloud"], ["endpoint", "Endpoint"],
        ["identity", "Identity"], ["ot_ics", "OT / ICS"], ["observability", "Observability"],
        ["compliance", "Compliance"], ["business", "Business"], ["other", "Other"]
    ];

    var STEPS = [
        { id: "content", title: "Get content", view: "ucm_content_admin", link: "Content Administration",
            text: "Import use cases from the content provider or from an offline bundle." },
        { id: "discover", title: "Discover", view: "ucm_inventory", link: "Data Inventory",
            text: "Find which indexes and sourcetypes have data in this environment." },
        { id: "assess", title: "Assess", view: "ucm_readiness", link: "Readiness",
            text: "Check each use case's requirements against what discovery found." },
        { id: "choose", title: "Choose", view: "ucm_catalogue", link: "Content Catalogue",
            text: "Browse and filter use cases and add the ones you want to your backlog (also see Backlog)." },
        { id: "deploy", title: "Validate and deploy", view: "ucm_deployments", link: "Deployments",
            text: "Validate the search, then draft, approve and deploy it as a disabled saved search." },
        { id: "monitor", title: "Monitor", view: "ucm_coverage", link: "Coverage",
            text: "See MITRE ATT&CK and regulation coverage and the dashboards generated by the app." }
    ];

    /* The first step that has no result yet; derived only from stored state. */
    function nextStep(facts) {
        if (!facts.catalogueKnown || !facts.catalogueTotal) { return facts.catalogueKnown ? "content" : null; }
        if (!facts.discoveryKnown) { return null; }
        if (!facts.discoveryAt) { return "discover"; }
        if (!facts.readinessKnown) { return null; }
        if (!facts.assessedTotal) { return "assess"; }
        return "choose";
    }

    var facts = { catalogueKnown: false, catalogueTotal: 0, discoveryKnown: false, discoveryAt: "",
        readinessKnown: false, assessedTotal: 0 };
    var cardBody = {};
    var stepNodes = {};

    function card(id, title) {
        var body = el("div", {}, el("div", { "class": "ucm-loading", text: "Loading…" }));
        cardBody[id] = body;
        return el("div", { "class": "ucm-card" }, el("h3", { text: title }), body);
    }

    function fill(id, nodes) { ucm.clear(cardBody[id]); [].concat(nodes).forEach(function (n) { if (n) { cardBody[id].appendChild(n); } }); }
    function failed(id, err) {
        fill(id, ucm.stateBox("error", "Not available.", err && err.message ? err.message : "The request failed."));
    }

    function refreshSteps() {
        var next = nextStep(facts);
        STEPS.forEach(function (s) {
            var n = stepNodes[s.id];
            if (!n) { return; }
            n.card.setAttribute("class", "ucm-card ucm-step" + (s.id === next ? " ucm-step-next" : ""));
            ucm.clear(n.tag);
            if (s.id === next) { n.tag.appendChild(ucm.badge("next step", "info")); }
        });
    }

    function loadCatalogue() {
        $.when(ucm.get("catalog", { count: 1 }), ucm.get("sync", { limit: 1 })).done(function (cat, sync) {
            var ps = sync.provider_state || {};
            facts.catalogueKnown = true;
            facts.catalogueTotal = cat.total || 0;
            if (!facts.catalogueTotal) {
                fill("catalogue", [el("div", { "class": "ucm-big", text: "0" }),
                    el("div", { "class": "ucm-sub", text: "No use cases imported yet." }),
                    el("a", { href: "ucm_content_admin", text: "Get content" })]);
            } else {
                fill("catalogue", [el("div", { "class": "ucm-big", text: String(facts.catalogueTotal) }),
                    el("div", { "class": "ucm-sub", text: "active use cases in the local catalogue" }),
                    el("dl", { "class": "ucm-kv" },
                        el("dt", { text: "Last sync (UTC)" }), el("dd", { text: ps.last_success_at || "never" }),
                        el("dt", { text: "Content version" }), el("dd", { text: ps.last_good_version || "none imported" })),
                    el("a", { href: "ucm_catalogue", text: "Open the catalogue" })]);
            }
            refreshSteps();
        }).fail(function (err) { failed("catalogue", err); });
    }

    function loadDiscovery() {
        ucm.get("discovery", { limit: 1 }).done(function (d) {
            var s = d.state || {};
            var t = s.totals || {};
            facts.discoveryKnown = true;
            facts.discoveryAt = s.last_completed_at || "";
            if (!facts.discoveryAt) {
                fill("discovery", [el("div", { "class": "ucm-big", text: "never" }),
                    el("div", { "class": "ucm-sub", text: "Discovery has not completed yet." }),
                    el("a", { href: "ucm_inventory", text: "Run discovery" })]);
            } else {
                fill("discovery", [el("div", { "class": "ucm-sub", text: "Last completed (UTC)" }),
                    el("div", { "class": "ucm-big ucm-small", text: facts.discoveryAt }),
                    el("div", { "class": "ucm-sub", text: (t.pairs === undefined ? "?" : t.pairs) + " index/sourcetype pairs in " +
                        (t.indexes_eligible === undefined ? "?" : t.indexes_eligible) + " indexes" +
                        (t.truncated ? " (result truncated)" : "") }),
                    el("a", { href: "ucm_inventory", text: "Open the data inventory" })]);
            }
            refreshSteps();
        }).fail(function (err) { failed("discovery", err); });
    }

    function loadReadiness() {
        ucm.get("readiness/summary").done(function (r) {
            var s = r.state || {};
            facts.readinessKnown = true;
            facts.assessedTotal = r.total || 0;
            if (!facts.assessedTotal) {
                fill("readiness", [el("div", { "class": "ucm-big", text: "not assessed" }),
                    el("div", { "class": "ucm-sub", text: r.discovery_completed_at
                        ? "Discovery is done; the use cases have not been assessed yet."
                        : "Assessment needs a completed discovery first." }),
                    el("a", { href: "ucm_readiness", text: "Open Readiness" })]);
            } else {
                var counts = el("div", { "class": "ucm-actions" });
                ucm.READINESS_STATES.forEach(function (st) {
                    counts.appendChild(el("a", { href: "ucm_readiness?state=" + st, "class": "ucm-home-count" },
                        ucm.readinessBadge(st), " ", String((r.by_state || {})[st] || 0)));
                });
                var older = s.discovery_at && r.discovery_completed_at && s.discovery_at !== r.discovery_completed_at;
                fill("readiness", [el("div", { "class": "ucm-sub", text: "Last assessment (UTC): " + (s.last_success_at || "never") +
                        " · " + facts.assessedTotal + " use cases assessed" }),
                    counts,
                    older ? ucm.stateBox("info", "Results are older than the latest discovery.",
                        "They were computed from the discovery of " + s.discovery_at + ".") : null,
                    el("div", { "class": "ucm-sub", text: "Hover a state for its rule. " +
                        "A state is a judgement from the checks that could be made, not a guarantee that data is present." })]);
            }
            refreshSteps();
        }).fail(function (err) { failed("readiness", err); });
    }

    function stepCard(s, index) {
        var tag = el("span", { "class": "ucm-step-tag" });
        var node = el("div", { "class": "ucm-card ucm-step" },
            el("div", { "class": "ucm-step-head" }, el("span", { "class": "ucm-step-no", text: String(index + 1) }),
                el("strong", { text: s.title }), tag),
            el("div", { "class": "ucm-sub", text: s.text }),
            el("a", { href: s.view, text: s.link }));
        stepNodes[s.id] = { card: node, tag: tag };
        return node;
    }

    function section(title, sub) {
        var body = Array.prototype.slice.call(arguments, 2);
        return el("div", { "class": "ucm-section" }, el("h3", { text: title }),
            sub ? el("div", { "class": "ucm-sub", text: sub }) : null, body);
    }

    var GUIDE_VIEWS = [
        ["ucm_catalogue", "Content Catalogue", "browse and filter imported use cases"],
        ["ucm_inventory", "Data Inventory", "what discovery found in this environment"],
        ["ucm_readiness", "Readiness", "assessment of each use case, with a legend for every state"],
        ["ucm_backlog", "Backlog", "your selected, deferred and rejected use cases"],
        ["ucm_deployments", "Deployments", "draft, approve, deploy, verify and roll back"],
        ["ucm_coverage", "Coverage", "MITRE ATT&CK and regulation mapping"],
        ["ucm_dashboards", "Dashboards", "generated dashboards"],
        ["ucm_overview", "Overview", "catalogue charts read from the app's lookups"]
    ];
    var GUIDE_TOPICS = ["Installing and checking the KV Store", "Users and roles", "Loading content (remote sync, offline bundles)",
        "Using each view", "Configuration (ucm.conf)", "Upgrading", "Troubleshooting", "REST endpoints and security notes"];

    function guideSection() {
        return section("User guide", "",
            ucm.stateBox("info", "The user guide is in development.",
                "It will be added here once it is written. Until then, the views and the operator guide cover the topics below."),
            el("div", { "class": "ucm-cards" },
                el("div", { "class": "ucm-card" }, el("h3", { text: "Views" }), el("ul", { "class": "ucm-list" },
                    GUIDE_VIEWS.map(function (v) { return el("li", {}, el("a", { href: v[0], text: v[1] }), ": " + v[2]); }))),
                el("div", { "class": "ucm-card" }, el("h3", { text: "Operator guide topics" }),
                    el("div", { "class": "ucm-sub", text: "docs/OPERATOR_GUIDE.md in the project repository describes:" }),
                    el("ul", { "class": "ucm-list" }, GUIDE_TOPICS.map(function (t) { return el("li", { text: t }); })))));
    }

    function domainSection() {
        return section("Explore by domain", "Opens the Domain dashboard for one monitoring domain.",
            el("div", { "class": "ucm-domain-grid" }, [["*", "All domains"]].concat(DOMAIN_LABELS).map(function (d) {
                return el("a", { "class": "ucm-card ucm-card-link ucm-domain", href: "ucm_domain?form.domain=" + encodeURIComponent(d[0]) },
                    el("strong", { text: d[1] }));
            })));
    }

    var FLAG_LABEL = { in_backlog: "In your backlog", deferred: "You deferred this", bookmarked: "You bookmarked this" };
    var EXCLUDED_LABEL = { not_in_active_catalogue: "not in the active catalogue", already_deployed: "already deployed",
        rejected_by_you: "rejected by you", blocked: "blocked", not_ready: "not ready", insufficient_evidence: "insufficient evidence",
        has_blockers: "with unmet critical requirements", quality_flagged: "left out by the review-quality option",
        no_data_seen: "with no data seen for what they read" };
    var QUALITY_OPTION = ["ai_reviewed", "unreviewed"];
    var PART_LABEL = [["readiness", "readiness score"], ["criticality", "criticality"], ["mitre_gain", "new MITRE coverage"],
        ["coverage", "requirement coverage"]];

    function recommendationItem(it) {
        var flags = (it.flags || []).map(function (f) {
            return ucm.badge(f === "deployment_in_progress" ? "Deployment " + String(it.deployment_state || "").replace(/_/g, " ") : FLAG_LABEL[f] || f, "info");
        });
        var parts = PART_LABEL.map(function (p) { return p[1] + " " + ((it.score_parts || {})[p[0]] || 0); }).join(" + ");
        return el("div", { "class": "ucm-card ucm-recommendation" },
            el("div", {}, ucm.providerBadge(String(it.content_id || "").split(":")[0]),
                el("a", { href: "ucm_usecase?id=" + encodeURIComponent(it.content_id), text: it.title }),
                el("span", { "class": "ucm-sub ucm-mono", text: " " + it.content_id })),
            el("div", { "class": "ucm-actions" }, ucm.readinessBadge(it.state), ucm.criticalityBadge(it.criticality), flags),
            el("div", { "class": "ucm-sub", text: "Draft score " + it.draft_score + " = " + parts }),
            el("details", { "class": "ucm-details" }, el("summary", { text: "Why this use case" }),
                el("ul", { "class": "ucm-list" }, (it.reasons || []).map(function (r) { return el("li", { text: r }); }))));
    }

    function recommendationEmpty(data) {
        var excluded = data.excluded || {};
        var why = Object.keys(excluded).map(function (k) { return excluded[k] + " " + (EXCLUDED_LABEL[k] || k); }).join(", ");
        switch (data.empty) {
        case "no_catalogue":
            return el("div", {}, ucm.stateBox("empty", "No use cases have been imported yet.", "Recommendations need content in the catalogue."),
                el("a", { href: "ucm_content_admin", text: "Get content" }));
        case "no_discovery":
            return el("div", {}, ucm.stateBox("empty", "Discovery has not completed yet.", "Recommendations need to know what data this environment has."),
                el("a", { href: "ucm_inventory", text: "Run discovery" }));
        case "no_assessment":
            return el("div", {}, ucm.stateBox("empty", "The use cases have not been assessed yet.", "Discovery is done; assess the catalogue to get recommendations."),
                el("a", { href: "ucm_readiness", text: "Open Readiness" }));
        default:
            return el("div", {}, ucm.stateBox("empty", "No use case is eligible right now.",
                "A use case is eligible when it is ready (or partially ready with no unmet critical requirement), not rejected by you and not deployed." +
                (why ? " Left out: " + why + "." : "")),
                el("a", { href: "ucm_readiness", text: "Open Readiness" }));
        }
    }

    function renderRecommendations(body, data) {
        ucm.clear(body);
        if (data.empty) { body.appendChild(recommendationEmpty(data)); return; }
        var w = (data.formula && data.formula.weights) || {};
        var pct = function (k) { return Math.round(100 * (w[k] || 0)) + "%"; };
        if ((data.exclude_quality || []).length) {
            body.appendChild(el("div", { "class": "ucm-sub", text: "Left out by your option: use cases flagged " +
                data.exclude_quality.map(function (f) { return ucm.QUALITY_FLAGS[f] ? ucm.QUALITY_FLAGS[f][0] : f; }).join(" or ") +
                (data.excluded && data.excluded.quality_flagged ? " (" + data.excluded.quality_flagged + " otherwise eligible)" : "") + "." }));
        }
        body.appendChild(el("div", { "class": "ucm-sub", text: "Showing " + data.items.length + " of " + data.eligible_total + " eligible use cases. " +
            "Draft score = " + pct("readiness") + " readiness score + " + pct("criticality") + " criticality + " + pct("mitre_gain") +
            " new MITRE coverage + " + pct("coverage") + " requirement coverage. The weights are a starting point, not measured. " +
            "Ready use cases come before partially ready ones. This is a suggestion from stored results; nothing is selected or deployed for you." }));
        body.appendChild(el("div", { "class": "ucm-cards" }, data.items.map(recommendationItem)));
    }

    function recommendationSlot() {
        var body = el("div", {}, el("div", { "class": "ucm-loading", text: "Loading…" }));
        var seq = 0;
        var box = el("input", { type: "checkbox", name: "exclude_quality", "aria-label": "Leave out AI-reviewed and unreviewed use cases" });
        function fetch() {
            var mine = ++seq;
            var params = box.checked ? { exclude_quality: QUALITY_OPTION.join(",") } : {};
            ucm.get("readiness/recommendations", params).done(function (data) { if (mine === seq) { renderRecommendations(body, data); } })
                .fail(function (err) {
                    if (mine !== seq) { return; }
                    ucm.clear(body).appendChild(ucm.stateBox("error", "Recommendations are not available.", err && err.message ? err.message : "The request failed."));
                });
        }
        box.addEventListener("change", fetch);
        var node = el("div", { "class": "ucm-section", id: "ucm-home-recommendations" }, el("h3", { text: "Recommended next" }),
            el("div", { "class": "ucm-sub", text: "Use cases that look ready to adopt, from the stored readiness results and your own selections." }),
            el("label", { "class": "ucm-check", title: "Off by default. Review flags are shown on every use case; this only changes this list." },
                box, " Leave out AI-reviewed and unreviewed use cases"),
            body);
        fetch();
        return node;
    }

    ucm.clear(root).appendChild(el("div", {},
        el("div", { "class": "ucm-header" }, el("h2", { text: "SUNavigator" }),
            el("div", { "class": "ucm-sub", text: "Discover, assess, select, validate and deploy monitoring use cases. " +
                "Deployments are always created disabled and by default need a second person's approval." })),
        section("Where things stand", "Read from the app's own stored state, not from a live search.",
            el("div", { "class": "ucm-cards" }, card("catalogue", "Catalogue"), card("discovery", "Last discovery"),
                card("readiness", "Readiness"))),
        section("From content to monitoring", "The steps in order. The highlighted step is the first one with no result yet.",
            el("div", { "class": "ucm-cards ucm-journey" }, STEPS.map(stepCard))),
        recommendationSlot(),
        domainSection(),
        guideSection()));

    loadCatalogue();
    loadDiscovery();
    loadReadiness();
}
