"""Dashboard templates rendered to Simple XML 1.1 (D-032).

Templates are code; parameters are validated against allowlists and every
value is XML-escaped. Generated dashboards only read this app's KV lookups or
reference saved searches deployed by this app (``<search ref>``, which shows
the latest scheduled results), so they add no new search logic.
"""

from typing import Any, Callable, Dict, List
from xml.sax.saxutils import escape, quoteattr

from ..errors import ValidationError

DOMAINS = ("security", "infrastructure", "network", "application", "database", "cloud", "endpoint",
           "identity", "ot_ics", "observability", "compliance", "business", "other")
MAX_PANELS = 20
MARKER = "Generated by SUNavigator"


def _domain(params: Dict[str, Any], required: bool) -> str:
    value = str(params.get("domain") or "")
    if not value and not required:
        return ""
    if value not in DOMAINS:
        raise ValidationError("domain must be one of %s" % ", ".join(DOMAINS))
    return value


def _label(domain: str) -> str:
    return domain.replace("_", "/").title() if domain else "All domains"


def _panel(title: str, query: str, viz: str = "table", extra: str = "") -> str:
    return (
        "    <panel>\n      <title>%s</title>\n      <%s>\n        <search>\n          <query>%s</query>\n"
        "          <earliest>-24h</earliest>\n          <latest>now</latest>\n        </search>\n%s"
        "      </%s>\n    </panel>\n" % (escape(title), viz, escape(query), extra, viz))


def _wrap(label: str, description: str, rows: List[List[str]]) -> str:
    body = "".join("  <row>\n%s  </row>\n" % "".join(row) for row in rows)
    return ('<dashboard version="1.1" theme="light" hideEdit="false">\n  <label>%s</label>\n'
            "  <description>%s</description>\n%s</dashboard>\n" % (
                escape(label), escape("%s. %s" % (MARKER, description)), body))


def _domain_filter(domain: str) -> str:
    return ' | search domains="%s"' % domain if domain else ""


def render_domain_overview(params: Dict[str, Any], context: Dict[str, Any]) -> Dict[str, str]:
    domain = _domain(params, True)
    f = _domain_filter(domain)
    catalogue = "| inputlookup ucm_catalog_lookup where provider_status=\"active\"%s" % f
    rows = [
        [_panel("Use cases by criticality", catalogue + " | stats count by criticality | sort - count", "chart",
                '        <option name="charting.chart">pie</option>\n'),
         _panel("Readiness", "| inputlookup ucm_readiness_lookup%s | stats count by state | sort - count" % f,
                "chart", '        <option name="charting.chart">bar</option>\n')],
        [_panel("Deployments", "| inputlookup ucm_deployments_lookup | lookup ucm_catalog_lookup _key as catalog_key "
                "OUTPUT domains%s | stats count by state live_status" % f),
         _panel("Use cases by category", catalogue + " | stats count by category_name | sort - count | head 15")],
        [_panel("Ready but not deployed", "| inputlookup ucm_readiness_lookup where state=\"ready\"%s "
                "| lookup ucm_deployments_lookup catalog_key as _key OUTPUT live_status "
                "| where isnull(live_status) OR live_status=\"absent\" | table content_id title criticality score "
                "| sort - score" % f)],
    ]
    return {"label": "SUNavigator %s overview" % _label(domain),
            "xml": _wrap("SUNavigator %s overview" % _label(domain),
                         "Catalogue, readiness and deployment state for the %s domain." % _label(domain), rows)}


def render_deployed_searches(params: Dict[str, Any], context: Dict[str, Any]) -> Dict[str, str]:
    domain = _domain(params, False)
    searches = [s for s in context.get("deployed") or [] if not domain or domain in (s.get("domains") or [])]
    if not searches:
        raise ValidationError("no deployed searches match; deploy use cases first")
    panels = []
    for s in searches[:MAX_PANELS]:
        panels.append(
            "    <panel>\n      <title>%s</title>\n      <table>\n        <search ref=%s></search>\n"
            "        <option name=\"count\">10</option>\n      </table>\n    </panel>\n" % (
                escape("%s (%s)" % (s["title"], s["live_status"])), quoteattr(s["saved_search"])))
    rows = [panels[i:i + 2] for i in range(0, len(panels), 2)]
    rows.insert(0, [_panel(
        "Scheduler runs (24 h)",
        "index=_internal sourcetype=scheduler app=\"sunavigator\" savedsearch_name=\"SUN - *\" "
        "| stats count as runs latest(status) as last_status max(_time) as last_run sum(result_count) as results "
        "by savedsearch_name | convert ctime(last_run)")])
    label = "SUNavigator deployed searches: %s" % _label(domain)
    return {"label": label,
            "xml": _wrap(label, "Latest scheduled results of searches deployed by the app (%d shown)."
                         % min(len(searches), MAX_PANELS), rows)}


TEMPLATES: Dict[str, Dict[str, Any]] = {
    "domain_overview": {
        "title": "Domain overview",
        "description": "Catalogue, readiness and deployment panels for one monitoring domain.",
        "params": [{"name": "domain", "required": True, "choices": list(DOMAINS)}],
        "render": render_domain_overview,
    },
    "deployed_searches": {
        "title": "Deployed searches",
        "description": "One panel per deployed search (latest scheduled results) plus scheduler health.",
        "params": [{"name": "domain", "required": False, "choices": list(DOMAINS)}],
        "render": render_deployed_searches,
    },
}


def template_list() -> List[Dict[str, Any]]:
    return [{"id": k, "title": v["title"], "description": v["description"], "params": v["params"]}
            for k, v in TEMPLATES.items()]


def render(template_id: str, params: Dict[str, Any], context: Dict[str, Any]) -> Dict[str, str]:
    template = TEMPLATES.get(template_id)
    if template is None:
        raise ValidationError("unknown template", {"allowed": list(TEMPLATES)})
    fn: Callable[..., Dict[str, str]] = template["render"]
    return fn(params, context)


def view_name(template_id: str, params: Dict[str, Any]) -> str:
    suffix = str(params.get("domain") or "all")
    return "ucm_gen_%s_%s" % (template_id, suffix)
