"""Deterministic export of the deployed revision of each use case (T-25, D-052).

The bundle is a Splunk ``savedsearches.conf`` text plus a JSON manifest. It is
built only from stored workflow records, so the same records always produce the
same bytes: stanzas sort by saved-search name, keys sort, and no export time is
written. Live Splunk state (enabled or disabled, drift) is not part of the
export; it describes approved content.
"""

from typing import Any, Dict, List, Optional, Sequence, Tuple

from .. import conf
from ..errors import ConflictError
from ..util import sha256_text
from .savedsearch import APP_NAME
from .spec import saved_search_name, settings_for, spl_hash

FORMAT = "ucm.export/1"
HEADER = [
    "Generated by Splunk Use Case Navigator (%s) from the deployed revision of each use case." % FORMAT,
    "Do not edit by hand: regenerate from the app. Saved searches are exported disabled.",
]


def conf_search(spl: str) -> str:
    """The SPL as a .conf file reads it back: trimmed lines, no outer blank lines."""
    return "\n".join(line.strip() for line in (spl or "").strip().splitlines())


def _deployed(doc: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    number = doc.get("deployed_revision")
    if not number:
        return None
    for rev in doc.get("revisions") or []:
        if rev.get("rev") == number:
            return rev
    return None


def _entry(doc: Dict[str, Any], rev: Dict[str, Any]) -> Tuple[str, Dict[str, Any], Dict[str, str]]:
    name = (doc.get("saved_search") or {}).get("name") or saved_search_name(doc.get("record_id", ""),
                                                                           doc.get("title", ""))
    search = conf_search(rev["spl"])
    settings = settings_for(rev, doc["content_id"], disabled=True)
    settings["search"] = search
    manifest = {
        "content_id": doc["content_id"], "title": doc.get("title", ""), "record_id": doc.get("record_id", ""),
        "saved_search": name, "revision": rev["rev"], "spl_source": rev.get("spl_source", ""),
        "approved_by": rev.get("approved_by", ""), "approved_at": rev.get("approved_at", ""),
        "deployed_at": rev.get("deployed_at", ""), "content_source_hash": rev.get("content_source_hash", ""),
        "cron_schedule": rev["cron"], "alert_mode": rev["alert_mode"], "severity": rev["severity"],
        "spl_sha256": spl_hash(rev["spl"]), "conf_search_sha256": sha256_text(search),
        "whitespace_normalized": search != rev["spl"],
        "stanza_sha256": sha256_text(conf.write_stanza(name, settings)),
    }
    return name, manifest, settings


def build_bundle(docs: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    entries: List[Tuple[str, Dict[str, Any], Dict[str, str]]] = []
    skipped: List[Dict[str, str]] = []
    for doc in docs:
        content_id = doc.get("content_id", "")
        if not doc.get("deployed_revision"):
            continue
        rev = _deployed(doc)
        if rev is None:
            skipped.append({"content_id": content_id, "reason": "deployed revision is missing from history"})
            continue
        if not rev.get("approved_by"):
            skipped.append({"content_id": content_id, "reason": "deployed revision has no approver"})
            continue
        try:
            entries.append(_entry(doc, rev))
        except (conf.ConfError, KeyError) as err:
            skipped.append({"content_id": content_id, "reason": str(err)})
    entries.sort(key=lambda e: (e[0], e[1]["content_id"]))
    names = [e[0] for e in entries]
    if len(set(names)) != len(names):
        raise ConflictError("two deployed use cases share a saved-search name; rename one before exporting",
                            {"code": "duplicate_saved_search"})
    text = conf.write([(name, settings) for name, _, settings in entries], header=HEADER)
    skipped.sort(key=lambda s: s["content_id"])
    manifest = {
        "format": FORMAT, "app": APP_NAME, "count": len(entries),
        "entries": [e[1] for e in entries], "skipped": skipped,
        "file": {"name": "savedsearches.conf", "sha256": sha256_text(text)},
    }
    return {"format": FORMAT, "filename": "savedsearches.conf", "content": text,
            "sha256": sha256_text(text), "count": len(entries), "skipped": len(skipped), "manifest": manifest}
